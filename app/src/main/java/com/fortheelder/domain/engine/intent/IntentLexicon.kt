package com.fortheelder.domain.engine.intent

/**
 * 一条意愿词条。
 *
 * [term] 是**规范名**，界面上显示它；[phrases] 是用户真会说出嘴的写法。两者分开是为了
 * 「用户说的是毛笔字，界面回的是书法」——把同义写法归并成一件可命名的事，方便以后
 * 同一件兴趣只出现一次。但用户的**原文一个字都不改**，逐字留在 `IntentHit.evidence` 里。
 */
data class IntentTerm(val term: String, val phrases: List<String>)

/**
 * 意愿识别用的词表。
 *
 * 这个文件里**只有词，没有判断逻辑**（判断写在 `IntentScanner`）。分开的唯一理由是：
 * 「常伴到底听得懂哪些话」必须是一份能逐行读、能逐条核对、能放心删改的清单，而不是
 * 散落在几十个 `if` 里的隐式知识。
 *
 * 收录原则——只收**同时**满足下面两条的说法：
 * 1. 55~65 岁刚退休的人在闲聊里真的会这么讲；
 * 2. 说了之后能落到**一件具体的事**上（有名字、能被聊起来）。
 *
 * 宁可少收。词表里每多一个含糊的词，就多一种把用户的话听错的可能；而听错比没听懂更伤——
 * 见 docs/01 的 AC-06.2「无法判断时输出不识别，不得猜」。
 */
object IntentLexicon {

    /**
     * 句子切分点。
     *
     * **逗号不在里面**：中文口语里的逗号常常只是换气，一个完整意思会横跨好几个逗号
     * （「我一直想学书法，就是不知道从哪儿下手」）。按逗号切开会把「想学」和「书法」
     * 拆到两段去，反而漏识别。
     */
    const val sentenceBreaks = "。！？；!?;\n\r"

    /**
     * 兴趣的**正面提示词**。
     *
     * 只有「提示词」和「主题」出现在**同一句**里，才认为用户说了想做某件事。光有提示词
     * （「我想学点什么」）不知道想学什么，光有主题（「书法挺好的」）不知道他自己想不想，
     * 两种情况都不产出——不猜。
     *
     * 匹配时**最长优先**：「我一直想学书法」里 `一直想` 会盖住 `想学` 和 `想`，
     * 所以 cue 报的是 `一直想`，片段是「一直想学书法」。这是有意的：更长的提示词
     * 信息量更大，而且结果稳定可复现。
     *
     * 收录了裸的 `想`：它是中文里最常用的愿望标记，而「必须同时命中主题」这条要求
     * 已经挡掉了绝大多数误判（「想睡觉」没有主题、「想不起来」含否定词）。
     * 代价记在 records/04 的已知问题里。
     */
    val interestCues: List<String> = listOf(
        "有点兴趣", "琢磨着想", "感兴趣", "愿意学", "想学着", "想学学",
        "一直想", "早就想", "打算学", "想了解", "想看看", "想试试",
        "想学", "想练", "想玩", "喜欢", "爱好", "想试",
        "想",
    )

    /**
     * 否定词。**只要一句话里出现任意一个，这句话就不产出任何兴趣**（状态和请求不受影响）。
     *
     * 为什么整句丢掉而不是做「否定 + 喜好」两个维度：需求里没有「用户明确说讨厌某件事」
     * 的场景（docs/01 的 FR-06 只讲发现意愿），造一个用不上的维度就是发明需求。
     * 而做「把否定作用在最近的词上」这类局部判断，中文口语里的拆解规则极其复杂，
     * 写出来的一定是错的。所以选**宁可漏，不猜**——与 AC-06.2 一致。
     *
     * 单独一个 `别` **没有**收进来：`我特别想学书法` 里的「特别」会把整句误杀，
     * 而靠提醒词能挡住的场景（「别学书法了」没有正面提示词，本来就不产出）不需要它。
     *
     * 已知代价：`不错`、`不着急`、`不忙` 这些不含否定义的词也会把整句带走。见 records/04。
     */
    val negationMarkers: List<String> = listOf("不", "没", "算了", "懒得")

    /**
     * 兴趣主题。需要与 [interestCues] 同句共现才产出。
     *
     * 不收那些**可能只是购买意图或随口一提**的词：`相机`、`球`、`书`、`手机`（单品）都不在。
     * 以「手机」为例，只有 `用手机` / `智能手机` 这类带动作的说法才算「想学会用」，
     * 否则「手机没电了」也会被当成兴趣。
     */
    val interestTopics: List<IntentTerm> = listOf(
        IntentTerm("书法", listOf("毛笔字", "练毛笔字", "书法")),
        IntentTerm("下棋", listOf("下象棋", "下围棋", "象棋", "围棋", "下棋")),
        IntentTerm("摄影", listOf("拍点照片", "拍照片", "摄影", "拍照", "照相")),
        IntentTerm("唱歌", listOf("唱老歌", "唱两句", "唱歌")),
        IntentTerm("戏曲", listOf("黄梅戏", "京剧", "唱戏", "听戏", "戏曲")),
        IntentTerm("跳舞", listOf("广场舞", "交谊舞", "跳舞")),
        IntentTerm("养花", listOf("摆弄花草", "养绿植", "养花", "种花")),
        IntentTerm("钓鱼", listOf("垂钓", "钓鱼")),
        IntentTerm("打太极", listOf("太极拳", "打太极", "太极")),
        IntentTerm("出去走走", listOf("出去旅游", "出去走走", "出去玩", "旅游", "旅行")),
        IntentTerm("做饭", listOf("学做菜", "做饭", "烧菜", "下厨")),
        IntentTerm("看书", listOf("读小说", "看书", "读书")),
        IntentTerm("用手机", listOf("用智能手机", "手机上的功能", "用手机", "智能手机")),
    )

    /**
     * 状态。用户说的不是愿望，是**当下的事实**，所以不需要提示词，词本身出现就算命中。
     *
     * 为什么把状态和兴趣分开：两种话要引出完全不同的回应。对「想学书法」可以往后聊，
     * 对「睡不着」绝不该顺势推销任何活动——那正是这个项目要避免的。
     */
    val statePhrases: List<IntentTerm> = listOf(
        IntentTerm("睡不好", listOf("睡不踏实", "半夜老醒", "夜里总醒", "睡不着", "睡不好", "失眠")),
        IntentTerm("身上疼", listOf("腿脚不利索", "膝盖疼", "关节疼", "腰疼", "腿疼")),
        IntentTerm("一个人在家", listOf("家里就我一个", "屋里空落落的", "一个人在家", "没人说话")),
        IntentTerm("记性不如从前", listOf("记性不好", "记性差", "老忘事", "总忘事")),
        IntentTerm("没事做", listOf("一天到晚没事", "不知道干什么", "闲得慌", "没事做")),
        IntentTerm("吃饭不规律", listOf("吃饭没准点", "不想吃饭", "吃不下")),
        IntentTerm("心里闷", listOf("闷得慌", "提不起劲", "心里闷", "心里空")),
    )

    /**
     * 请求。用户直接把话递过来了，同样不需要提示词。
     *
     * 这里只识别「他在要什么」这一类，**不识别具体要的是什么**（要找什么地方、查什么事情），
     * 那需要真正听懂内容，现在做不到。所以 term 写得宽泛且诚实，界面上也不会假装听懂了细节。
     */
    val requestPhrases: List<IntentTerm> = listOf(
        IntentTerm(
            "想找人搭把手",
            listOf("能不能帮我", "帮我看一下", "帮我想想", "帮我个忙", "搭把手"),
        ),
        IntentTerm(
            "想打听一件事",
            listOf("帮我找找", "帮我查查", "帮我问问", "帮我打听", "我想知道"),
        ),
    )
}
