package com.fortheelder.domain.play

import kotlin.random.Random

/**
 * 倒着点。
 *
 * 盘面跟 [SchulteGrid] **一模一样**：5×5 个格子里摆着打乱的 1 到 25，摆法每局都不同。
 * 这一局不同的只有一处——该点的先后**反过来了**，从 25 点回 1。
 *
 * 同一批字、同一张盘，换的只是「先点哪个」。这不是换了个说法重抄一遍舒尔特：正序数数靠的是
 * 扫一眼就抓住下一个数在哪（注意广度），倒着点每一步都得对着一屏数字往回找、还得压住
 * 「看见小的就想点」的那只手，考的是认知灵活性里那条「换个方向还做不做得到」。两件事用
 * 的是同一个引擎，但不是同一个任务——[OrderRound] 只认「相等」和「先后」两条，它本来就不
 * 知道先后是顺着排的还是倒着排的。
 *
 * ## 这一条是怎么加进来的（第 148 轮）
 *
 * [PlayCatalog] 的类注释把「加一个游戏要动多少」按代价分了四种，第一种是
 * **「规则是已有的，只多写一条 `PlayGame(...)`，界面与测试都不动」**。那一条从第 12 轮写成
 * 文字起就没兑现过——第 12 轮只识别出它，第 17 / 41 / 48 / 144 轮落地的四个游戏各走的是
 * 另外三种。这一局是第一种的**第一次兑现**：产品码只新增这一个文件、另动几处注释；其中
 * `ui/play/PlayScreen.kt` 一个字没动，`ui/play/PlayVoice.kt` 也只改了一处注释、没多出行为分支
 * （两者那几处 `when` 都是按 [PlayRound] 的**子类型**分支的，不是按 `gameId` 分的），既有测试也没为它加过一条。
 *
 * 三条边界跟舒尔特那三条是同一套，理由也同一套（都在结构上，不在界面的自觉上）：
 *
 * - **只算这一局用了多久**，算完只活在这一屏里。库里没有一列可以放用时，「上次 41 秒、
 *   这次 32 秒」这种比较不会出现（AC-12.2、DR-09）。
 * - **点错没有代价**。倒序下两句提示仍然是实话：点到还没轮到的小数字，[PlayHint.NOT_YET]
 *   说「这个还在后面，不急」——在这个局里确实是「还轮不到」；点到已经点过的大数字，
 *   [PlayHint.ALREADY_DONE] 说「这个已经点过了，换一个」。两句都不用为倒序另写。
 * - **中途退出不留痕迹**。这一局的全部状态就是一个 [OrderRound] 值；这一页关掉，它就没了。
 */
object ReverseGrid {

    const val ID = "countdown-5x5"

    /** 边长。5×5 = 25 格。与 [SchulteGrid.SIDE] 同值，但各写各的：两局的盘面哪天分开了，改这里不影响那边。 */
    const val SIDE = 5

    /** 1 到 25。**倒过来**才是该点的顺序；它本身不参与洗牌，洗的只是摆法。 */
    private val numbers: List<String> = (1..(SIDE * SIDE)).map { it.toString() }

    val game: PlayGame = PlayGame(
        id = ID,
        name = "倒着点",
        howTo = "格子里是打乱的 1 到 25，这回从大到小点：25、24、23……挨个点一遍。点错了也不要紧，接着点就是。",
        columns = SIDE,
        longestSeconds = 180,
        deal = ::deal,
    )

    /**
     * 摆一局。25 个数字一个不少，只是位置每次不同，而**该点的顺序是倒着的**。
     *
     * `shuffled` 返回新列表，[numbers] 本身不变；`reversed` 同样返回新列表。两处都要新列表，
     * 否则第二次开局点的顺序就跟着变了，而「从大到小挨个点」是这个游戏唯一的一条规矩。
     *
     * 返回的是具体的 [OrderRound]：这一局的形状本来就是它，调用的人不必强转。
     */
    fun deal(random: Random): OrderRound = OrderRound(
        gameId = ID,
        cells = numbers.shuffled(random),
        order = numbers.reversed(),
    )
}
