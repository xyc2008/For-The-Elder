package com.fortheelder.domain.play

/**
 * 能玩的游戏的目录。
 *
 * **只登记做完的。** 计划里往后还有几个候选，第 17 轮把其中三个都判了一遍：记一记（翻牌）
 * 要按住「第一张翻开来停多久再盖回去」这条规矩，那就得让领域层持有时间，顺延；反应速度要
 * 计时，与 AC-11.2「不评价快慢」、AC-11.3「不催」直接冲突，判退；连续减七原本看着要输入
 * 数字，但它的**缩减形式**（每题三个数、三选一）既不读时钟也不用打字，第 17 轮以「算一算」
 * 落地。三条候选的判定表在 `records/03-架构决策记录.md` 的 ADR-018。
 * 目录里有一条点进去玩不了的东西，比目录里只有一条糟得多（AC-11.4）；先塞一个占位游戏进来
 * 「把框架撑起来」也是另一种错法——那样框架看着是通的，用户点进去却是空的，而这个应用的
 * 每一条入口都必须是能用的。
 *
 * 第 41 轮把欠的那笔账还上了：记一记落地，**而顺延它的那条理由同时被实测推翻**——翻回去
 * 由用户点一下驱动，不由表驱动，领域层一秒都不用跟时间打交道（ADR-038）。判据当初写错，这一次
 * 不是靠「把时间放进来」绕过去的，是把那条规矩本身换掉了。
 *
 * 加一个游戏要动多少，第 12 轮实测出两种，第 17 轮验出第三种，第 41 轮又验出第四种：
 * - 规则是**已有的**（再来一个按顺序点的、再来一个找一样的）：只在这里多写一条
 *   `PlayGame(...)`，界面与测试都不动。
 * - 规则是**新的**，而且「一局里要记什么」也变了（找一样的就是这一种）：除了目录这一条，
 *   还要加一个 [PlayRound] 实现，并在界面上加一个分支。
 * - 规则是新的，**但动词还是「点某一格」**（算一算就是这一种）：界面一行都不用改，代价是
 *   界面里那几个 `when` 会当场编译不过，把该补的分支报出来（详见 ADR-018）。
 * - 规则是新的，**而且「格子上现在显示什么」也归领域层管**（记一记就是这一种）：还是不用
 *   在界面上加分支，但要在 [PlayRound] 上加一个带默认实现的口子 [PlayRound.faceOf]——
 *   头三个游戏一个字没改，界面只多读了这一句（详见 ADR-038）。
 * 第 12 轮这里写的「加第二个游戏不用改结构」只对第一种成立，已按实测更正。
 */
object PlayCatalog {

    val games: List<PlayGame> =
        listOf(SchulteGrid.game, FindPair.game, SubtractSeven.game, Memory.game)

    /** 目录里的第一个游戏。只有一个游戏时界面直接进它，不去问用户挑哪个。 */
    val first: PlayGame get() = games.first()
}
