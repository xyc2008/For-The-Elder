package com.fortheelder.domain.play

/**
 * 能玩的游戏的目录。
 *
 * **只登记做完的。** 计划里往后还有三个（记一记、反应速度、连续减七），它们在没有真的
 * 能玩之前不会出现在这个列表里——目录里有一条点进去玩不了的东西，比目录里只有一条糟得多
 * （AC-11.4）。做周全的另一种错法是先塞一个占位游戏进来「把框架撑起来」：
 * 那样框架看着是通的，用户点进去却是空的，而这个应用的每一条入口都必须是能用的。
 *
 * 加一个游戏要动多少，第 12 轮的实测答案分两种：
 * - 规则是**已有的**（再来一个按顺序点的、再来一个找一样的）：只在这里多写一条
 *   `PlayGame(...)`，界面与测试都不动。
 * - 规则是**新的**（找一样的就是这一种）：除了目录这一条，还要加一个 [PlayRound] 实现，
 *   并在界面上加一个分支——因为新规则连「一局里要记什么」都不一样。
 * 上一轮这里写的「加第二个游戏不用改结构」只对第一种成立，已按实测更正。
 */
object PlayCatalog {

    val games: List<PlayGame> = listOf(SchulteGrid.game, FindPair.game)

    /** 目录里的第一个游戏。只有一个游戏时界面直接进它，不去问用户挑哪个。 */
    val first: PlayGame get() = games.first()
}
