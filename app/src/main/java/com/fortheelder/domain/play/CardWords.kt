package com.fortheelder.domain.play

/**
 * 能拿来当牌面的那批字。
 *
 * 这二十个字原先长在 [FindPair.words] 里。第 41 轮加记一记，它也要往牌面写字，于是提到这里
 * 由两个游戏共用；第 144 轮加找一个不一样的，它是第三个来借字的。**单一来源是本项目的一贯立场**：
 * 同一批字在两处各写一份，迟早会对不上，
 * 而对不上的那种情况没人会测（两边的测试各自都过）。
 *
 * 选字的标准是三条，一条都不能松：
 *
 * - **两个字**。四列摆下来不会挤成两行——三字词在窄屏上会折行，一行高度不一样看着就乱。
 * - **都是这个年纪的人一眼认得的日常物件**。这里不考记忆力、不考识字量，牌面不该是门槛。
 * - **彼此之间没有一个是另一个的一部分**（测试会两两查）。否则「看着像」会变成真的分不清：
 *   找一样就没了判据——两张牌看起来都像要找的那张；记一记更糟，会出现两张「像是同一张」
 *   却配不成对的牌，用户会一直在那儿点；找一个不一样则认不出哪两个是别样的。
 *
 * 这二十个字也过了词表（[ClaimWords]）：全是物件名，一个医疗、功效、评价人的词都没有。
 */
object CardWords {

    /** 全部可以拿来做牌面的字。 */
    val all: List<String> = listOf(
        "桔子", "苹果", "白菜", "豆腐", "茶壶",
        "蒲扇", "毛衣", "布鞋", "象棋", "毛笔",
        "藤椅", "凉席", "算盘", "棉被", "雨伞",
        "桂花", "月饼", "核桃", "花生", "石榴",
    )
}
