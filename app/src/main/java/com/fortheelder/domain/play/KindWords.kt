package com.fortheelder.domain.play

/**
 * 「找同类」用的分好类的字表。
 *
 * 为什么不复用 [CardWords.all]：那个表的二十个字是**给找一样和记一记当牌面**用的，
 * 它刻意做到「两两之间没有一个是另一个的一部分」，为的是「看着像」不会变成真的分不清。
 * 这份表要的东西正相反——它得能**按类别分组**。拿那二十个字试过分组（`records/03` ADR-043
 * 记了这次实测），无论怎么分都凑不出「至少三组、每组至少四个」，所以另开这一份。
 * 单一来源这条立场没有被破坏：两份表**各管一件事**，而且**刻意零重叠**——同一个词
 * 不会既是牌面又是某一类的成员，测试会两两查（[KindWordsTest]）。
 *
 * 选字的标准是三条，与牌面表同源：
 *
 * - **两个字**。四列摆下来不会挤成两行。
 * - **都是这个年纪的人一眼认得的日常物件**。这里不考识字量，字面不该是门槛。
 * - **类别靠生活常识一眼分得开**。五类的边界都不需要想：水果、蔬菜、穿的、厨房里的、文具。
 *
 * 有一处措辞是刻意收窄的：这一类叫「**穿的**」而不是「衣物」。帽子、手套、围巾那几样
 * 严格说是「戴的」而不是「穿的」，归进去会让用户犹豫——他犹豫的这一刻，这个游戏就不再是
 * 「看看就好」了。所以那几个词一个都没收，只留穿上身的四样。
 */
object KindWords {

    /** 全部类别，每类四个两字词。 */
    val kinds: List<Kind> = listOf(
        Kind("水果", listOf("香蕉", "葡萄", "桃子", "西瓜")),
        Kind("蔬菜", listOf("萝卜", "黄瓜", "茄子", "豆角")),
        Kind("穿的", listOf("衬衫", "棉袄", "袜子", "裤子")),
        Kind("厨房里的", listOf("铁锅", "菜刀", "饭碗", "汤勺")),
        Kind("文具", listOf("铅笔", "橡皮", "尺子", "本子")),
    )

    /** 全部词，扁平成一层，方便词表纪律测试两两查。 */
    val all: List<String> = kinds.flatMap { it.words }
}
